import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const DEFAULT_SRC = "C:/Users/Pc/Desktop/adwolf website/Adwolf Portfolio/Adwolf Portfolio";
const OUT_ROOT = path.resolve("public/work");
const DATA_FILE = path.resolve("data/work-images.ts");
const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

const SLUG_BY_FOLDER = {
  "A47": "a47",
  "Cable Masters": "cablemaster",
  "CRQ Tech": "crq-technology",
  "IHOPE": "ihop",
  "Marcel's": "marcels",
  "Mary Brown's Chicken": "mary-browns-chicken",
};

const KNOWN_SLUGS = [
  "a47", "aztec-chocolate", "cablemaster", "chatterbox-cafe", "costa",
  "crq-technology", "dealicious-mealz", "divine-dates", "fad", "gulabo",
  "himalaya", "ihop", "innovative-pvt-ltd", "marcels", "mary-browns-chicken",
  "mcon", "pidoko-kids", "pie-in-the-sky", "prestige", "suncore-solar", "the-melt",
];

function slugFor(folder) {
  if (SLUG_BY_FOLDER[folder]) return SLUG_BY_FOLDER[folder];
  return folder
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

const arg = process.argv.slice(2);
const src = arg.find((a) => !a.startsWith("--")) ?? DEFAULT_SRC;
const force = arg.includes("--force");

async function listImageFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = entries
    .filter((e) => e.isFile() && IMAGE_EXTS.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  return files;
}

function pad(n) {
  return String(n).padStart(2, "0");
}

async function convertTo(srcFile, outFile, maxWidth, quality) {
  const meta = await sharp(srcFile)
    .rotate()
    .resize({ width: maxWidth, withoutEnlargement: true })
    .webp({ quality })
    .toFile(outFile);
  return { w: meta.width, h: meta.height };
}

async function exists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const folders = (await readdir(src, { withFileTypes: true })).filter((e) => e.isDirectory());
  const result = {};
  const seen = new Set();
  let totalBytes = 0;

  for (const d of folders) {
    const slug = slugFor(d.name);
    if (!slug) continue;
    const dir = path.join(src, d.name);
    const files = await listImageFiles(dir);
    if (files.length === 0) continue;

    seen.add(slug);
    const outDir = path.join(OUT_ROOT, slug);
    await mkdir(outDir, { recursive: true });

    const images = [];
    for (let i = 0; i < files.length; i++) {
      const num = pad(i + 1);
      const outName = `${num}.webp`;
      const outPath = path.join(outDir, outName);
      if (force || !(await exists(outPath))) {
        await convertTo(path.join(dir, files[i]), outPath, 1600, 80);
      }
      const info = await sharp(outPath).metadata();
      images.push({ src: `/work/${slug}/${outName}`, w: info.width, h: info.height });
    }

    const coverPath = path.join(outDir, "cover.webp");
    if (force || !(await exists(coverPath))) {
      await convertTo(path.join(dir, files[0]), coverPath, 900, 80);
    }
    const coverInfo = await sharp(coverPath).metadata();
    const cover = { src: `/work/${slug}/cover.webp`, w: coverInfo.width, h: coverInfo.height };

    result[slug] = { cover, images };

    for (const f of [coverPath, ...images.map((i) => path.join(outDir, path.basename(i.src)))]) {
      totalBytes += (await stat(f)).size;
    }

    const names = images.map((i) => `${i.w}x${i.h}`).join(", ");
    console.log(`  ${slug.padEnd(22)} ${files.length} img  [${names}]`);
  }

  const missing = KNOWN_SLUGS.filter((s) => !seen.has(s));
  const unknown = [...seen].filter((s) => !KNOWN_SLUGS.includes(s));
  if (missing.length) console.log(`WARN missing slugs: ${missing.join(", ")}`);
  if (unknown.length) console.log(`WARN unknown slugs (not in known list): ${unknown.join(", ")}`);

  const imgLit = (i) => `{ src: ${JSON.stringify(i.src)}, w: ${i.w}, h: ${i.h} }`;
  const entries = Object.entries(result)
    .map(([slug, v]) => {
      const imgs = v.images.map(imgLit).join(", ");
      return `  ${JSON.stringify(slug)}: {\n    cover: ${imgLit(v.cover)},\n    images: [${imgs}],\n  },`;
    })
    .join("\n");

  const body = [
    "// GENERATED by scripts/import-work-images.mjs - do not edit by hand.",
    "export type WorkImage = { src: string; w: number; h: number };",
    "",
    "export const workImages: Record<string, { cover: WorkImage; images: WorkImage[] }> = {",
    entries,
    "};",
    "",
  ].join("\n");

  await mkdir(path.dirname(DATA_FILE), { recursive: true });
  await writeFile(DATA_FILE, body, "utf8");
  console.log(`\nWrote ${DATA_FILE}`);
  console.log(`Public work images: ${Object.values(result).reduce((n, v) => n + v.images.length, 0)}`);
  console.log(`Total size of public/work: ${(totalBytes / 1024 / 1024).toFixed(2)} MB`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});